"""Validate and emit exact post-combat Flow-node boundaries; no runtime access."""
import argparse,json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[3]
def generate():
 d=json.loads((ROOT/'mods/tower/data/terminal_flows.json').read_text(encoding='utf-8'))
 rows=[];seen=set()
 def guid(s):
  assert re.fullmatch(r'[0-9A-F]{8}(?:-[0-9A-F]{8}){3}',s),s
  return '{'+','.join('0x'+x+'u' for x in s.split('-'))+'}'
 for x in d['rules']:
  key=(x['asset_guid'],x['node_guid']);assert key not in seen;seen.add(key)
  assert x['node_type'].endswith('_C') and re.fullmatch('[0-9a-f]{64}',x['source_sha256'])
  rows.append('    {'+guid(x['asset_guid'])+','+guid(x['node_guid'])+','+json.dumps(x['flow'],ensure_ascii=False)+'},')
 return '// Generated by gen_terminal_flows.py; exact cooked GUIDs, not class/name guesses.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace tower::terminal {\nusing Guid=std::array<uint32_t,4>;\nstruct Rule {Guid asset,node;const char* flow;};\ninline constexpr Rule kRules[]={\n'+'\n'.join(rows)+'\n};\ninline const Rule* Find(const Guid& asset,const Guid& node){for(const auto& r:kRules)if(r.asset==asset && r.node==node)return &r;return nullptr;}\n}\n'
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
 p=ROOT/'mods/tower/src/terminal_flows.generated.h';text=generate()
 if args.check:
  assert p.read_text(encoding='utf-8')==text,'terminal Flow header stale'
 else:p.write_text(text,encoding='utf-8',newline='\n')
 print('TERMINAL_FLOWS_OK')
