"""影塔 Boss 原生场地：从 Codex 的雾门关联数据（mods/tower/data/native_arena_links.json，地图单元里的刷怪点 + 战斗区域 + 雾门，
codex/tower-data fff0af6）给每只池内 Boss 选一处场地，生成 src/native_spots.generated.h。
  python -I mods/tower/tools/gen_native.py [--check] [--report]

选法（2026-10-31 实测后改）：同一只 Boss 多个候选时按
  明确 Boss 战斗组 > 有名字的刷怪点（无名多是剧情 / 关卡实例里的占位，铁杀的无名 G3 把人送进了树里）> Boss 自己的原生地图
  > 关联了雾门 > 战斗区域已解析
排序；性能测试图（PSOCombat 等）和"不是已解析玩法摆放"的不要。
玩家落点 = 战斗区域中心（解析到时），否则 Boss 出生点；朝向对着 Boss。出生点不等于玩家落点（Codex 场地笔记）。
"""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "mods/tower/data/native_arena_links.json"
OUT = ROOT / "mods/tower/src/native_spots.generated.h"
SKIP_LEVELS = {"PSOCombat", "PSOSeq", "PsoCollection", "ServerCheck"}
# Boss 数据里的原生地图（bosses.json native_map）→ 世界名
MAP_LEVEL = {"XiGu": "PBZ_Xigu_WP", "PangZhen": "PBZ_Pangzhen_WP", "MeiGuHu": "PBZ_Pangzhen_WP", "FuJiZhiLin": "PBZ_Fujizhilin_WP",
             "ZhengDaoDaYing": "PBZ_Zhengdaodaying_WP", "LuJiaCun": "PBZ_Zhengdaodaying_WP", "DengDingShanDao": "PBZ_DengDingShanDao_WP",
             "XiMeng": "PBZ_Ximeng_WP", "DuanHunYa": "PBZ_Duanhun_WP", "HouJie": "PBZ_Houjie_WP", "ZhuLinGuWu": "PBZ_WP_ZhuLinGuWu"}


def pool():
    s = (ROOT / "mods/tower/src/boss_pool.generated.h").read_text(encoding="utf-8")
    return re.findall(r'\{"(/[^"]+)", "([^"]*)", [0-9.]+, \'(.)\', "([^"]*)", "([^"]*)", (true|false)\}', s)


def usable(x):
    hints = x.get("selection_hints") or []
    return x["level"] not in SKIP_LEVELS and "not_a_resolved_gameplay_placement" not in hints and x.get("boss_transform")


# 用户实测指定的原生剧情场地（同一 Boss 多个候选、排序会选错的）：排第一
PREFER_SPAWNERS = {
    "BP_AISpawner_C_UAID_BCFCE7058A8B278002_1148021495",  # 勾魂：庞镇地面 ShuangGou（不是高空试炼空间 Hu_G3_2）；用户 2026-11-05
    "BP_AISpawner_C_UAID_BCFCE7078B5A82B202_1202356523",  # 斩骑：庞镇地面 ZhanQiGuiChai（不是高空试炼空间 Hu_G3_1）；用户 2026-11-05
}

def rank(x, native):
    hints = x.get("selection_hints") or []
    return (x.get("spawner_actor") not in PREFER_SPAWNERS,
            x.get("group_name") != "Boss" and "explicit_boss_group" not in hints,
            "unnamed_spawner" in hints or not x.get("spawner"),
            x["level"] != MAP_LEVEL.get(native, ""),
            not x.get("fog_doors"),
            not x.get("domain_resolved"),
            x.get("spawner") or "", x.get("id", ""))


def pick(cands, native):
    c = [x for x in cands if usable(x)]
    return sorted(c, key=lambda x: rank(x, native))[0] if c else None


def landing(x):
    """玩家落点：战斗区域中心（解析到时）；朝向对着 Boss 出生点"""
    boss = x["boss_transform"]["position"]
    dom = x.get("domain_transform") if x.get("domain_resolved") else None
    at = dom["position"] if dom else boss
    dx, dy = boss[0] - at[0], boss[1] - at[1]
    yaw = math.degrees(math.atan2(dy, dx)) if abs(dx) + abs(dy) > 50 else x["boss_transform"]["rotation"].get("Yaw", 0.0)
    return at, yaw, boss


def render(items):
    by = {}
    for x in items:
        by.setdefault(x["class_path"], []).append(x)
    lines = ["// Generated by mods/tower/tools/gen_native.py. Do not edit.", "#pragma once", "#include <string_view>", "namespace tower {",
             f'inline constexpr std::string_view kNativeSource = "{hashlib.sha256(DATA.read_bytes()).hexdigest()}";',
             "// 池内 Boss 的原生场地：level = 世界名；x y z yaw = 玩家落点（战斗区域中心，朝向 Boss）；bx by bz = Boss 出生点；",
             "// group = 明确 Boss 战斗组；fog = 关联了雾门",
             "struct NativeSpot { std::string_view path, level; double x, y, z, yaw, bx, by, bz; bool group, fog; };",
             "inline constexpr NativeSpot kNativeSpots[] = {"]
    for path, name, cls, ident, native, scene in pool():
        x = pick(by.get(path) or [], native)
        if not x:
            continue
        at, yaw, boss = landing(x)
        hints = x.get("selection_hints") or []
        group = x.get("group_name") == "Boss" or "explicit_boss_group" in hints
        lines.append("    {" + ", ".join([json.dumps(path), json.dumps(x["level"])] + [repr(round(float(v), 1)) for v in (*at, yaw, *boss)] +
                                         ["true" if group else "false", "true" if x.get("fog_doors") else "false"]) + "},")
    lines += ["};", "}  // namespace tower", ""]
    return "\n".join(lines).encode("utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    items = json.loads(DATA.read_text(encoding="utf-8"))["items"]
    if a.report:
        by = {}
        for x in items:
            by.setdefault(x["class_path"], []).append(x)
        miss = []
        for path, name, cls, ident, native, scene in pool():
            x = pick(by.get(path) or [], native)
            if not x:
                miss.append(f"{name}（{cls}{'·场景' if scene == 'true' else ''}）")
                continue
            at, yaw, boss = landing(x)
            hints = x.get("selection_hints") or []
            print(f"{cls}{'*' if scene == 'true' else ' '} {name:22} {x['level']:24} 落点({at[0]:.0f},{at[1]:.0f},{at[2]:.0f}) "
                  f"组={x.get('group_name') or '-'} 雾门={len(x.get('fog_doors') or [])} 刷怪点={x.get('spawner') or '无名'}")
        print(f"\n没有可用原生场地 {len(miss)} 只：" + "、".join(miss))
    data = render(items)
    if a.check:
        if not OUT.exists() or OUT.read_bytes().replace(b"\r\n", b"\n") != data.replace(b"\r\n", b"\n"):
            raise SystemExit("native_spots.generated.h 过期：运行 python -I mods/tower/tools/gen_native.py")
        return
    OUT.write_bytes(data)


if __name__ == "__main__":
    main()
