"""影塔成长数据：从解包表（notes/dump，本地、不入库）生成 src/growth_data.generated.h。
内容：主武器 / 影之武装（类型、特效所在等级）、能力修行节点（线、列、前置、上限、原生花费）、药（每级使用次数）、饰品（分类、可精炼）。
塔的玩法规则（点数、药档、奖励）不在这里，在 src/tower_growth.h。
用法：python -I mods/tower/tools/gen_growth.py [--check]（--check：表和生成结果不一致则失败；本机没有解包表时跳过）
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DUMP = ROOT / "notes/dump"
TABLES = DUMP / "tables/ProjectPBZ/Content/PBZContent/DataTable/UI"
OUT = ROOT / "mods/tower/src/growth_data.generated.h"

# 剧情 / 演出专用的兵器行（同一把兵器的马车战、序章、木制版），不进塔的兵器池
STORY_WEAPONS = {"WoodenSword", "WoodenSwordHun", "Tang_HorseCartCombat", "TangPrologue", "HeiMoShangPrologue"}
LINES = {"HeiShi": 0, "ShaChiHupo": 1, "MemoryFlower": 2, "TopRongShuZhixin": 3, "BottomRongShuZhixin": 4}
ACC_TYPES = {"Attack": 0, "Survival": 1, "Support": 2}


def rows(name):
    return json.loads((TABLES / name).read_text(encoding="utf-8"))[0]["Rows"]


def zh_names():
    flat = {}

    def walk(x):
        if isinstance(x, dict):
            for k, v in x.items():
                if isinstance(v, str):
                    flat[k] = v
                else:
                    walk(v)
    walk(json.loads((DUMP / "Game.zh-Hans.json").read_text(encoding="utf-8")))
    return flat


def q(s):
    return json.dumps(s, ensure_ascii=False)


def render():
    sources = ["DT_WeaponData.json", "DT_ShaqiWeaponData.json", "DT_AbilityNodesTable.json", "DT_MedicineTable.json", "DT_Accessory.json"]
    digest = hashlib.sha256(b"".join((TABLES / s).read_bytes() for s in sources)).hexdigest()
    zh = zh_names()
    out = ["// Generated by mods/tower/tools/gen_growth.py from the unpacked data tables. Do not edit.", "#pragma once",
           "#include <array>", "#include <string_view>", "namespace tower::growth {",
           f'inline constexpr std::string_view kSource = "{digest}";', ""]

    # 兵器：特效等级 = 升到该级时有 GEDatas 的那一级（升级数组第 i 项 = 升到 i+2 级）
    out += ["// kind 0 主武器 / 1 影之武装；type 主武器类型 0 单手 1 双持 2 双手（影之武装为 -1）；perks 特效所在等级（≤30，最多 8 个，0 结尾）",
            "struct Weapon { std::string_view id, name; int kind, type, maxLevel; std::array<int, 8> perks; bool snapSoul; };",
            "inline constexpr Weapon kWeapons[] = {"]
    seen = set()
    types = {"EWeaponType::Blade": 0, "EWeaponType::DoubleBlade": 1, "EWeaponType::GreatBlade": 2}
    for kind, (fn, key, snap) in enumerate((("DT_WeaponData.json", "WeaponUpLevelDatas", "WeaponSnapSoulData"),
                                           ("DT_ShaqiWeaponData.json", "ShaChiWeaponUpLevelData", "ShaChiWeaponSnapSoulData"))):
        for name, r in rows(fn).items():
            wid = r.get("ItemId")
            if not wid or wid in STORY_WEAPONS or (kind, wid) in seen:
                continue
            seen.add((kind, wid))
            ups = r.get(key) or []
            perks = [i + 2 for i, u in enumerate(ups) if (u.get("GEDatas") or u.get("PersistentGEDatas")) and i + 2 <= 30][:8]
            perks += [0] * (8 - len(perks))
            wtype = types.get(r.get("WeaponType"), -1) if kind == 0 else -1
            has_snap = bool(r.get(snap))
            out.append(f"    {{{q(wid)}, {q(name)}, {kind}, {wtype}, {len(ups) + 1}, {{{', '.join(map(str, perks))}}}, {'true' if has_snap else 'false'}}},")
    out += ["};", "inline constexpr int kWeaponCount = static_cast<int>(std::size(kWeapons));", ""]

    # 能力修行节点
    out += ["// line 0 黑石 / 1 杀气琥珀 / 2 记忆之花 / 3 榕树之心·上 / 4 榕树之心·下；parents 为 kNodes 下标（-1 无）；dust 原生花费（定塔内点数档位用）",
            "struct Node { std::string_view id, name; int line, column, maxLevel, dust; std::array<int, 2> parents; };",
            "inline constexpr Node kNodes[] = {"]
    nodes = list(rows("DT_AbilityNodesTable.json").values())
    index = {n["AbilityNodeItemID"]: i for i, n in enumerate(nodes)}
    for n in nodes:
        line = LINES[n["NodeType"].split("::")[1]]
        parents = [index[p] for p in (n.get("ParentNodes_RongShuZhiXin") or []) if p in index][:2]
        parents += [-1] * (2 - len(parents))
        name = zh.get(n["AbilityNodeName"]["Key"], n["AbilityNodeItemID"])
        out.append(f"    {{{q(n['AbilityNodeItemID'])}, {q(name)}, {line}, {n['Column']}, {n.get('MaxLevel', 1)}, {n.get('ConsumeDust', 0)}, {{{parents[0]}, {parents[1]}}}}},")
    out += ["};", "inline constexpr int kNodeCount = static_cast<int>(std::size(kNodes));", ""]

    # 药
    out += ["// uses：1–6 级每级的使用次数", "struct Medicine { std::string_view id, name, text; std::array<int, 6> uses; };",
            "inline constexpr Medicine kMedicines[] = {"]
    for name, m in rows("DT_MedicineTable.json").items():
        uses = [int(l.get("UseTimes", 0)) for l in m.get("MedicineLevelData", [])][:6]
        uses += [uses[-1] if uses else 1] * (6 - len(uses))
        text = zh.get((m.get("AbilityDesc") or [{}])[0].get("Key", ""), "")
        text = re.sub(r"<[^>]*>", "", text).strip().rstrip("。")  # 去富文本标签（按键 / 资源图标），保留整句效果
        out.append(f"    {{{q(m.get('ItemId') or m.get('ID'))}, {q(name)}, {q(text)}, {{{', '.join(map(str, uses))}}}}},")
    out += ["};", "inline constexpr int kMedicineCount = static_cast<int>(std::size(kMedicines));", ""]

    # 饰品：没有中文名的（未上线 / 内部）不进
    out += ["// type 0 攻击 / 1 生存 / 2 辅助；refine 可精炼的最高级", "struct Accessory { std::string_view id, name, text; int type, refine; };",
            "inline constexpr Accessory kAccessories[] = {"]
    for a in rows("DT_Accessory.json").values():
        name = zh.get(a["AccessoryName"]["Key"])
        if not name:
            continue
        # 只要效果（AccessoryDesc = Item_Accessory_FunctionDes_*，如"生命值+15%"），不要介绍（ShortIntroduction）；
        # 去掉富文本标签（<Niagara …/>、<img …/>）和句末句号。用户 2026-11-05：饰品匣只写效果
        text = re.sub(r"<[^>]*>", "", zh.get((a.get("AccessoryDesc") or {}).get("Key", ""), "")).strip().rstrip("。")
        if not text:
            text = zh.get((a.get("ShortIntroduction") or {}).get("Key", ""), "")
        out.append(f"    {{{q(a['ItemId'])}, {q(name)}, {q(text)}, {ACC_TYPES[a['AccessoryType'].split('::')[1]]}, {a.get('MaxRefineLevel', 1)}}},")
    out += ["};", "inline constexpr int kAccessoryCount = static_cast<int>(std::size(kAccessories));", "",
            "}  // namespace tower::growth", ""]
    return "\n".join(out).encode("utf-8")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    if not TABLES.is_dir():
        if args.check:
            print("growth data: no unpacked tables here, check skipped")
            raise SystemExit(0)
        raise SystemExit(f"unpacked tables not found: {TABLES}")
    data = render()
    if args.check:
        if not OUT.is_file() or OUT.read_bytes().replace(b"\r\n", b"\n") != data.replace(b"\r\n", b"\n"):
            raise SystemExit("growth data is stale: run mods/tower/tools/gen_growth.py")
    else:
        OUT.write_bytes(data)
        print(f"wrote {OUT}")
