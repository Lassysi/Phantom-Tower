"""Generate exact, directed native mechanism relationships; no name heuristics."""
import argparse, hashlib, json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'mods/tower/data/encounter_dependencies.json'
HEADER = ROOT / 'mods/tower/src/encounter_dependencies.generated.h'
p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args = p.parse_args()
data = json.loads(SOURCE.read_text(encoding='utf-8'))
edges = data['edges']
assert len({(e['owner'], e['target']) for e in edges}) == len(edges)
assert all(e['owner'] != e['target'] and e['owner'].endswith('_C') and e['target'].endswith('_C') and e['ability'] and e['sources'] for e in edges)
lines = ['// Generated by gen_encounter_dependencies.py. Source SHA256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
         '// Configured passive -> SummonInfos, not global actor exemptions. Static evidence; live acceptance remains per boss.',
         '#pragma once', '#include <array>', '#include <string_view>', 'namespace tower::encounter {',
         'struct Edge { std::string_view owner, target, ability; };', 'inline constexpr Edge kEdges[] = {']
for e in edges:
    lines.append('    {'+', '.join(json.dumps(e[k],ensure_ascii=False) for k in ('owner','target','ability'))+'},')
lines += ['};', 'inline constexpr size_t kEdgeCount = sizeof(kEdges) / sizeof(kEdges[0]);',
          '// Bounded graph walk: nested native summons are dependencies too. No phase/victory registration.',
          'inline std::string_view RequiredBy(std::string_view owner, std::string_view target) {',
          '    if (owner.empty() || target.empty() || owner == target) return {};',
          '    std::array<std::string_view, kEdgeCount + 1> queue{}; size_t head = 0, tail = 1; queue[0] = owner;',
          '    while (head < tail) {',
          '        const auto current = queue[head++];',
          '        for (const auto& e : kEdges) {',
          '            if (e.owner != current) continue;',
          '            if (e.target == target) return e.ability;',
          '            bool seen = false;',
          '            for (size_t i = 0; i < tail; ++i) seen |= queue[i] == e.target;',
          '            if (!seen && tail < queue.size()) queue[tail++] = e.target;',
          '        }', '    }', '    return {};', '}', '} // namespace tower::encounter', '']
expected = '\n'.join(lines)
if args.check:
    assert HEADER.read_text(encoding='utf-8') == expected, 'encounter dependency header is stale'
else: HEADER.write_text(expected, encoding='utf-8', newline='\n')
print(f'encounter dependencies: {len(edges)} edges, {len({e["owner"] for e in edges})} configured owner classes; OK')
