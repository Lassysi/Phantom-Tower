"""影塔擂台与钟表：从 mods/tower/data/arenas.json（Codex 数据，接近点 = 钟的传送点）和 shared/bells.json 生成
src/travel_data.generated.h。擂台中心由玩家在游戏里标定（{"cmd":"arena","value":"mark"}），存在
%LOCALAPPDATA%\PBZTower\arenas.local.txt，运行时覆盖接近点。
用法：python -I mods/tower/tools/gen_travel.py [--check]
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "mods/tower/src/travel_data.generated.h"


def render():
    araw = (ROOT / "mods/tower/data/arenas.json").read_bytes()
    braw = (ROOT / "shared/bells.json").read_bytes()
    arenas = json.loads(araw)["items"]
    bells = json.loads(braw)
    lines = ["// Generated by mods/tower/tools/gen_travel.py. Do not edit.", "#pragma once", "#include <string_view>",
             "namespace tower {",
             f'inline constexpr std::string_view kTravelSource = "{hashlib.sha256(araw + braw).hexdigest()}";',
             "struct ArenaDef { std::string_view id, map, bell; int zone; double x, y, z, yaw; };",
             "inline constexpr ArenaDef kArenas[] = {"]
    for a in arenas:
        p = a["approach"]
        if not p or not a["approach_bell"]:
            continue
        lines.append("    {" + ", ".join([json.dumps(a["id"]), json.dumps(a["map"]), json.dumps(a["approach_bell"]), str(int(a["zone"])),
                                         repr(float(p["x"])), repr(float(p["y"])), repr(float(p["z"])), repr(float(p["yaw"]))]) + "},")
    lines += ["};", "struct BellDef { std::string_view id; double x, y, z, yaw; };", "inline constexpr BellDef kBells[] = {"]
    for b in bells:
        lines.append("    {" + ", ".join([json.dumps(b["id"]), repr(float(b["x"])), repr(float(b["y"])), repr(float(b["z"])), repr(float(b["yaw"]))]) + "},")
    lines += ["};", "}  // namespace tower", ""]
    return "\n".join(lines).encode("utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="生成结果与已提交的不一致就失败")
    args = ap.parse_args()
    data = render()
    if args.check:
        if not OUT.exists() or OUT.read_bytes().replace(b"\r\n", b"\n") != data.replace(b"\r\n", b"\n"):
            raise SystemExit("travel_data.generated.h 过期：运行 python -I mods/tower/tools/gen_travel.py")
        return
    OUT.write_bytes(data)
    print(f"写出 {OUT}")


if __name__ == "__main__":
    main()
