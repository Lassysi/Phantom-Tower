# 小怪波次的怪物表（1.4.0）：从 shared/enemies.json 选普通怪 / 精英，按地图分到五个区，写 src/mobs.generated.h。
# 只收运行库目录里有的路径；Boss 池里已有的、骑马 / 飞行 / 半身 / 变体、章节不明的不收。
# 用法：python -X utf8 mods/tower/tools/gen_mobs.py
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[3]
enemies = json.loads((ROOT / 'shared/enemies.json').read_text(encoding='utf-8'))
pool = (ROOT / 'mods/tower/src/boss_pool.generated.h').read_text(encoding='utf-8')
catalog = (ROOT / 'src/core/features/world/enemy_catalog.generated.h').read_text(encoding='utf-8')

ZONES = {'XiGu': 1, 'FuJiZhiLin': 2, 'PangZhen': 3, 'HouJie': 3, 'MeiGuHu': 4, 'LuJiaCun': 4,
         'XiMeng': 5, 'DengDingShanDao': 5, 'ZhengDaoDaYing': 5}
SKIP_NAME = re.compile(r'骑|马匪|乌鸦|漂浮|半身|变体|剧情|教学|暂译|女娃|机灵鬼|狂犬')

rows, seen = [], set()
for e in enemies:
    if e['kind'] not in ('mob', 'elite') or not e.get('hp') or not e.get('name_zh'):
        continue
    if e['path'] in pool or e['path'] not in catalog or e['path'] in seen:
        continue
    if SKIP_NAME.search(e['name_zh']):
        continue
    zone = ZONES.get((e.get('chapter_or_map') or '').split('（')[0])
    if not zone:
        continue
    seen.add(e['path'])
    rows.append((zone, e['kind'] == 'elite', float(e['hp']), e['name_zh'], e['path']))
rows.sort()

out = ['// Generated by mods/tower/tools/gen_mobs.py. Do not edit.', '#pragma once', '#include <string_view>', 'namespace tower::mobs {',
       'struct Mob { int zone; bool elite; double hp; std::string_view name, path; };', 'inline constexpr Mob kMobs[] = {']
for zone, elite, hp, name, path in rows:
    out.append(f'    {{{zone}, {"true" if elite else "false"}, {hp:.0f}, "{name}", "{path}"}},')
out += ['};', '}  // namespace tower::mobs', '']
(ROOT / 'mods/tower/src/mobs.generated.h').write_text('\n'.join(out), encoding='utf-8', newline='\n')
for z in range(1, 6):
    print('zone', z, 'mobs', sum(1 for r in rows if r[0] == z and not r[1]), 'elites', sum(1 for r in rows if r[0] == z and r[1]))
