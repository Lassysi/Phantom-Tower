inline int FindCall(const uint8_t* p,size_t n,const uint8_t* pre,size_t pn,const uint8_t* post,size_t sn) {
    int found=-1;
    for(size_t i=0;p && i+pn+5+sn<=n;++i) if(!std::memcmp(p+i,pre,pn) && p[i+pn]==0xe8 && !std::memcmp(p+i+pn+5,post,sn)) {
        if(found>=0)return -1; found=static_cast<int>(i+pn);
    }
    return found;
}
inline int WrapperCall(const uint8_t* p,size_t n) {
    static constexpr uint8_t a[]={0x48,0x85,0xc0,0x49,0x8b,0xcf,0x48,0x89,0x74,0x24,0x20,0x40,0x0f,0x95,0xc7,0x48,0x03,0xf8,0x48,0x89,0x7b,0x20};
    static constexpr uint8_t b[]={0x4c,0x8d,0x9c,0x24,0x90,0x00,0x00,0x00,0x49,0x8b,0x5b,0x20};
    return FindCall(p,n,a,sizeof a,b,sizeof b);
}
inline int LeafCall(const uint8_t* p,size_t n) {
    static constexpr uint8_t a[]={0x48,0x8b,0xce,0x48,0x89,0x44,0x24,0x20};
    static constexpr uint8_t b[]={0x48,0x8b,0x5c,0x24,0x50,0x48,0x8b,0x74,0x24,0x58};
    return FindCall(p,n,a,sizeof a,b,sizeof b);
}
inline bool InnerSignature(const uint8_t* p,size_t n) {
    static constexpr uint8_t start[]={0x40,0x55,0x53,0x56,0x57,0x41,0x54,0x41,0x55,0x41,0x56,0x41,0x57,0x48,0x8d,0x6c,0x24,0xd8,0x48,0x81,0xec,0x28,0x01,0x00,0x00};
    return p && n>=sizeof start && !std::memcmp(p,start,sizeof start);
}
