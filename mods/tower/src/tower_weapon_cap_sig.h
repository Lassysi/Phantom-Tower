// Validated on build 26266538; relative call displacements are intentionally
// omitted. A changed wrapper or native formula disables the experimental path.
inline bool NativeSignature(const uint8_t* p, size_t n) {
    static constexpr uint8_t start[] = {0x48,0x89,0x5c,0x24,0x08,0x48,0x89,0x6c,0x24,0x10,0x48,0x89,0x74,0x24,0x18,0x57};
    static constexpr uint8_t tail[] = {0xb9,0x06,0,0,0,0x48,0x8b,0x6c,0x24,0x38,0x3b,0xf1,0x0f,0x4c,0xce,0x48,0x8b,0x74,0x24,0x40,0x83,0xc1,0x06,0x8d,0x0c,0x89,0x3b,0xcf,0x0f,0x4c,0xf9,0x8b,0xc7,0x48,0x83,0xc4,0x20,0x5f,0xc3};
    return p && n >= 0xa7 + sizeof tail && !std::memcmp(p, start, sizeof start) && !std::memcmp(p + 0xa7, tail, sizeof tail);
}
inline int WrapperCall(const uint8_t* p, size_t n) {
    static constexpr uint8_t suffix[] = {0x48,0x8b,0x5c,0x24,0x40,0x89,0x06,0x48,0x83,0xc4,0x20,0x5f,0x5e,0x5d,0xc3};
    int at = -1;
    for (size_t i = 0; p && i + 5 + sizeof suffix <= n; ++i)
        if (p[i] == 0xe8 && !std::memcmp(p + i + 5, suffix, sizeof suffix)) { if (at >= 0) return -1; at = static_cast<int>(i); }
    return at;
}
