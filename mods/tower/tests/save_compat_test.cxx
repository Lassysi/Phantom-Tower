static int g_checks = 0, g_fail = 0;
static void Check(bool ok, const char* what) {
    ++g_checks;
    if (!ok) { ++g_fail; std::printf("FAIL %s\n", what); }
}

int main() {
    using namespace tower;
    // Generated by the actual v1.3.5 Run::Save / Runner::Save after suspending
    // during boss 10, with a nonempty inventory and growth points.
    const auto fixtures = std::filesystem::path(__FILE__).parent_path() / "fixtures";
    auto read = [](const std::filesystem::path& path) { std::ifstream f(path, std::ios::binary); std::ostringstream s; s << f.rdbuf(); return s.str(); };
    const auto legacy = read(fixtures / "1.3.5-run.txt");
    Run old;
    Check(!legacy.empty() && old.Load(legacy), "1.3.5 suspended run loads");
    Check(old.floor == 9 && old.phase == Phase::Ready && old.jade == 345 && old.items[0] == 2, "legacy floor and inventory remain intact");
    Check(old.legacy, "a run from before 2.0.0 is recognised, so it is retired and the player starts a new run");
    Run fresh, reread;
    fresh.Start(7, 50);
    Check(reread.Load(fresh.Save()) && !reread.legacy, "a 2.0.0 run is not treated as an old run");
    const auto growth = read(fixtures / "1.3.5-growth.txt");
    growthrun::Runner oldGrowth;
    Check(!growth.empty() && growthrun::Runner::Load(growth, &oldGrowth) && oldGrowth.profile.temper == 7 && oldGrowth.profile.cultivate == 8 && !oldGrowth.profile.weapons.empty(),
          "1.3.5 growth, equipment and points load");
    Check(kItemCount >= static_cast<int>(std::size(frozen::kItems)), "items: no item removed");
    for (size_t i = 0; i < std::size(frozen::kItems) && i < static_cast<size_t>(kItemCount); ++i)
        if (kItems[i].id != std::string_view(frozen::kItems[i])) {
            std::printf("item slot %zu: saved as %s, now %s\n", i, frozen::kItems[i], std::string(kItems[i].id).c_str());
            Check(false, "items: saved index order unchanged (append only)");
        }
    Check(kWeaponDropCount >= static_cast<int>(std::size(frozen::kDrops)), "boss weapons: no row removed");
    for (size_t i = 0; i < std::size(frozen::kDrops) && i < static_cast<size_t>(kWeaponDropCount); ++i) {
        const std::string now = std::string(kWeaponDrops[i].stem) + "|" + std::string(kWeaponDrops[i].weapon);
        if (now != frozen::kDrops[i]) {
            std::printf("boss weapon slot %zu: saved as %s, now %s\n", i, frozen::kDrops[i], now.c_str());
            Check(false, "boss weapons: saved index order unchanged (append only)");
        }
    }
    Check(kShentongCount >= static_cast<int>(std::size(frozen::kShentong)), "shentong: no entry removed");
    for (size_t i = 0; i < std::size(frozen::kShentong) && i < static_cast<size_t>(kShentongCount); ++i)
        if (kShentong[i].id != std::string_view(frozen::kShentong[i])) {
            std::printf("shentong slot %zu: saved as %s\n", i, frozen::kShentong[i]);
            Check(false, "shentong: saved index order unchanged (append only)");
        }
    // 枚举值也写进存档（道具编号、奖励类型、局阶段）：只能在末尾追加
    const Item items[] = {Item::Heal, Item::Reroll, Item::Freeze, Item::Slow, Item::Sunder, Item::Shachi, Item::Intel, Item::Borrow, Item::Revive, Item::Guard, Item::Edge, Item::Break};
    for (int i = 0; i < static_cast<int>(std::size(items)); ++i) Check(static_cast<int>(items[i]) == i, "enum Item keeps v1.0.0 values");
    using K = rewards::Kind;
    const K kinds[] = {K::Blessing, K::TemperPack, K::CultivatePack, K::Weapon, K::Accessory, K::Refine, K::Medicine, K::Item, K::Jade, K::Attr, K::SoulToken};
    for (int i = 0; i < static_cast<int>(std::size(kinds)); ++i) Check(static_cast<int>(kinds[i]) == i, "enum rewards::Kind keeps v1.0.0 values");
    const Phase phases[] = {Phase::Idle, Phase::Ready, Phase::Fighting, Phase::Reward, Phase::Won, Phase::Lost};
    for (int i = 0; i < static_cast<int>(std::size(phases)); ++i) Check(static_cast<int>(phases[i]) == i, "enum Phase keeps v1.0.0 values");
    if (g_fail) { std::printf("TOWER_SAVE_COMPAT_FAILED %d/%d\n", g_fail, g_checks); return 1; }
    std::printf("TOWER_SAVE_COMPAT_OK %d checks (v1.0.0 save indexes still valid)\n", g_checks);
    return 0;
}
